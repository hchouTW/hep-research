#!/usr/bin/env python3
"""Write simcal-approvals.md: the decisions the author has given (quoted from Appendix E of Part B) and the approval packet of
every open item the decision index assigns to the author, with empty approval fields, followed by the items the author is asked
to confirm but that no phase waits for.
Usage: python3 -I tools/build_approvals.py   (run from the package root, after tools/build_decision_index.py)"""
import json, re
idx = json.load(open("simcal-decision-index.json", encoding="utf-8"))
SPEC_LINES = open("simulator-calibration-v7.37.4-clean-en.md", encoding="utf-8").read().split("\n")
GIVEN = [
 ("A1", "2026-11-09", "Class-1 proposals of `triage.md` (42 Appendix D entries other than D68), the merges D13 → D63 and D64 → D22, and the §19 items §19-11 and §19-14.1c",
  "Accept all class-1 proposals as `triage.md` writes them, and the merges D13 → D63 and D64 → D22, except D68: I will decide its denominator together with §19-14.1f and D3.",
  "Appendix E, \"Author's acceptance of 2026-11-09\""),
 ("A2", "2026-11-09", "Revision of D28 (seeds of the mapping runs, joint-pattern replicas, the θ-noise item of P5), en/research-D28.md",
  "proceed as recommended; put 'the true errors are highly correlated but the replicas are uncorrelated' in as a note",
  "Appendix E, \"D28 revision (author decision of 2026-11-09)\""),
 ("A3", "2026-11-09", "The M1 note of `decision-sheet.md`: U in the fixed-map mode",
  "Proceed as recommended; the fixed-map mode need not keep the linear construction; the second PDE-split route should be researched and taken into consideration.",
  "Appendix E, \"Author decision of 2026-11-09 (fixed-map mode)\""),
 ("A4", "2026-11-09", "The 24 plugin-source rules (b′), the three choices of the D28 verification (b″), and the proposals of D86 and D87",
  "I agree to adopt them",
  "Appendix E, \"Author's acceptance of 2026-11-09 (plugin-source rules, D28 choices, D86, D87)\""),
 ("A5", "2026-11-10", "The PDE split (§19-g4c; §6.7 \"PDE split\")",
  "Adopt in principle: route 2, route 3 when the PDE depends on wavelength, and a mandatory comparison with a nominal-PDE mapping run. Before writing, check the Geant4 `DielectricMetal` branch, revise the text on the four points, and then send it to independent verification.",
  "Appendix E, \"Author decision of 2026-11-10 (PDE split)\""),
]
TIE = {"D68": "decide with D3 and §19-14.1f (A1)", "D3": "decide with D68 and §19-14.1f (A1)", "D50": "decide with §19-14.1a", "D47": "decide with D52",
       "D45": "decide with the §7.4 rules of D57", "D84": "decide with §19-g9 and the G6 rows of §8.7", "D85": "decide with D84 and §19-g9", "D37": "D86 and D87 use its criterion"}
# Readings and recommendations from the author's decision-sheet.md (from triage.md), keyed by item name.
SHEET = {}
try:
    ds = open("decision-sheet.md", encoding="utf-8").read().split("\n")
    for i, l in enumerate(ds):
        m = re.match(r"^- \*\*((?:D\d+)|(?:§19-[0-9a-z.]+))\*\*(?: \([^)]*\))*(?: \([^)]*\([^)]*\)[^)]*\))?\.?\s*(.*)$", l)
        if m:
            t = re.sub(r"\s*Why conservative:.*$", "", m.group(2))
            SHEET.setdefault(m.group(1), "decision-sheet: " + t)
        m = re.match(r"^\*\*((?:D\d+)|(?:§19-[0-9a-z.]+)):", l)
        if m:
            rec = next((x for x in ds[i:i + 30] if x.startswith("- **Recommendation")), "")
            if rec: SHEET.setdefault(m.group(1), "decision-sheet (options a–c): " + rec[2:].replace("**", ""))
except FileNotFoundError:
    pass
def phase_key(b):
    m = re.search(r"\d", b or ""); return int(m.group()) if m else 9
def esc(s): return (s or "").replace("|", "/")
out = ["# Simulator calibration: approvals", "",
       "Record of the author's decisions on the specification (Part B) and the approval packet of the items still open. The rules are those of `g4sim-approvals.md`: "
       "each item is approved by the author, explicitly; silence or a related remark is not approval (`simcal-task.md`, Section E7, item 1). For each approved item "
       "the record holds the person, the date, and their words or a link to where they gave them. One explicit statement may cover several items if it names them. "
       "Generated by `tools/build_approvals.py` from `simcal-decision-index.json`; after an approval is recorded here, the author applies it to Part B (a new part of Appendix E) and the index is regenerated.", "",
       "## Decisions already given", "",
       "Each was given in Chinese in a Claude session and is quoted here in the translation that Appendix E of Part B records. Each is already applied in Part B.", "",
       "| Record | Date | Items | Person | Words (translation) | Where applied |", "| --- | --- | --- | --- | --- | --- |"]
for r in GIVEN:
    out.append(f"| {r[0]} | {r[1]} | {r[2]} | the author | “{r[3]}” | {r[4]} |")
out += ["", "Still open from these decisions: D68 together with §19-14.1f and D3 (A1). The A3 sentence on the second PDE-split route was answered by A5.", "",
        "## Approval packet: open items that need the author", "",
        "In the order of the phase they block. **Proposal or reading** is the first part of the entry's proposed resolution in Appendix D (\"Part B\"), or, where Part B gives none, the reading or the recommendation of the author's `decision-sheet.md` (\"decision-sheet\", from `triage.md`); both are cut at about 300 characters, so read the source in full. An empty cell means neither gives one. "
        "The author's `decision-sheet.md` (in this package) gives, phase by phase, the reading, the options and the recommendation for each item; "
        "its counts are of the 118 triage items and follow the triage classes, while this packet follows front matter line 38 (`simcal-decision-index.md`).", "",
        "| Item | Part B line | Where | Kind | Blocks | Proposal or reading (source) | Tie-in | Approved | Date | Words or link |", "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
rows = []
for r in idx["appendix_D"]:
    if r["kind"].startswith("needs the author"):
        pr = ("Part B: " + r["proposal"]) if r.get("proposal") else SHEET.get(r["item"], "")
        if r["kind"].startswith("needs the author (open part)"):
            txt = SPEC_LINES[r["line"] - 1]
            m = re.search(r"(Open for the author:.*?\.(?=\s|$)|\(\d\) for the author, [^;]*)", txt)
            if m: pr = "Part B, open part: " + m.group(1)
        rows.append((r["item"], r["line"], r["where"], r["kind"], r["blocks"], (pr or ("deferred: no reading yet" if "deferred" in r["kind"] else ""))[:320], TIE.get(r["item"], "")))
for r in idx["section_19"]:
    if r["kind"].startswith("needs the author"):
        rows.append((r["name"], r["line"], r["start"][:80], r["kind"], r["blocks"], (SHEET.get(r["name"], "") or ("deferred: no reading yet" if "deferred" in r["kind"] else ""))[:320], ""))
rows.sort(key=lambda x: (phase_key(x[4]), x[1]))
for it, ln, wh, kd, bl, pr, tie in rows:
    out.append(f"| {it} | {ln} | {esc(wh)} | {kd} | {bl} | {esc(pr)} | {tie} |  |  |  |")
conf = [r for r in idx["appendix_D"] + idx["section_19"] if r["status"] == "open" and not r["kind"].startswith("needs the author") and not r["kind"].startswith("settled")]
out += ["", f"{len(rows)} items.", "",
        "## Confirmations that no phase waits for", "",
        "These are implemented as Part B writes them (computation results, and, by front matter line 38, D19, D25 and the open §14.1 items of §19, whose body reading is implemented). "
        "The author's confirmation or veto is recorded here when given; a veto is applied by the author to Part B.", "",
        "| Item | Part B line | Kind | Blocks | Tie-in | Confirmed | Date | Words or link |", "| --- | --- | --- | --- | --- | --- | --- | --- |"]
for r in sorted(conf, key=lambda x: (phase_key(x["blocks"]), x["line"])):
    name = r.get("item") or r["name"]
    tie = "decide with D68 and D3 (A1)" if name == "§19-14.1f" else ("decide with D50" if name == "§19-14.1a" else TIE.get(name, ""))
    out.append(f"| {name} | {r['line']} | {r['kind']} | {r['blocks']} | {tie} |  |  |  |")
out += ["", f"{len(conf)} items.", ""]
open("simcal-approvals.md", "w", encoding="utf-8").write("\n".join(out))
print(len(rows), "in the packet;", len(conf), "confirmations")
