#!/usr/bin/env python3
"""Capability map (X3): validate docs/capability-map.json and write its table into docs/capability-map.md.

The map lists each capability with its owner, its state (`tool`: a shipped script or core module does it;
`documentation`: only guidance exists; `none`: absent) and whether it is in v1. Domains outside v1 name their
limited-support routing cases (`cases`), which tools/check_routing_static.py checks. `items` names the upgrade-plan
items that add or extend the capability; `enters_v1_with` names the item that moves a domain into v1.

Usage: python3 tools/capability_map.py [--check | --write]
  --check (default): validate the map and confirm the generated table is current; exit 0 ok, 1 otherwise.
  --write: validate, then rewrite the generated table. Output: JSON with `status`.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "docs" / "capability-map.json"
DOC = ROOT / "docs" / "capability-map.md"
OWNERS = {"hep-measurement", "hep-detector", "hep-theory", "hep-statistics", "hep-computing", "hep-ml",
          "hep-communication", "core", "contracts"}
STATES = ("tool", "documentation", "none")
BEGIN, END = "<!-- capability-map: generated by tools/capability_map.py -->", "<!-- /capability-map -->"


def load(path: Path = MAP) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def validate(m: dict) -> list[str]:
    errs, seen = [], set()
    for i, e in enumerate(m.get("capabilities", [])):
        where = f"row {i} ({e.get('id')})"
        if e.get("id") in seen:
            errs.append(f"{where}: duplicate id")
        seen.add(e.get("id"))
        if not e.get("capability"):
            errs.append(f"{where}: no capability text")
        owners = [o.strip() for o in str(e.get("owner", "")).split(",")]
        if not owners or any(o not in OWNERS for o in owners):
            errs.append(f"{where}: unknown owner {e.get('owner')!r}")
        if e.get("state") not in STATES:
            errs.append(f"{where}: state must be one of {STATES}")
        if not isinstance(e.get("v1"), bool):
            errs.append(f"{where}: v1 must be true or false")
        if e.get("v1") is False and len(owners) != 1:
            errs.append(f"{where}: a domain outside v1 names one closest owner")
    return errs


def table(m: dict) -> str:
    rows = ["| ID | Capability | Owner | State | In v1 | Items | Limited-support cases |", "|---|---|---|---|---|---|---|"]
    for e in m["capabilities"]:
        v1 = "yes" if e["v1"] else "no" + (f" (enters with {e['enters_v1_with']})" if e.get("enters_v1_with") else "")
        rows.append(f"| {e['id']} | {e['capability']} | {e['owner']} | {e['state']} | {v1} | "
                    f"{', '.join(e.get('items', []))} | {', '.join(e.get('cases', []))} |")
    return "\n".join(rows)


def render_into(text: str, m: dict) -> str:
    head, _, rest = text.partition(BEGIN)
    _, _, tail = rest.partition(END)
    return f"{head}{BEGIN}\n{table(m)}\n{END}{tail}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true")
    g.add_argument("--write", action="store_true")
    a = ap.parse_args()
    m = load()
    errs = validate(m)
    text = DOC.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        errs.append(f"{DOC.name} lacks the generated-table markers")
    new = render_into(text, m)
    if a.write and not errs and new != text:
        DOC.write_text(new, encoding="utf-8")
        text = new
    stale = new != text
    ok = not errs and not stale
    print(json.dumps({"status": "ok" if ok else "failed", "rows": len(m.get("capabilities", [])),
                      "v1_out": sum(1 for e in m.get("capabilities", []) if e.get("v1") is False),
                      "errors": errs, "stale_table": stale}, indent=1))
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
