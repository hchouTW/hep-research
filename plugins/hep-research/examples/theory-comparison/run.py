def figures(counts, fold_counts, obs_fit, lumi_obs, out):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    c = 0.5 * (RE[1:] + RE[:-1])
    fig, (ax, bx) = plt.subplots(1, 2, figsize=(10, 4))
    ax.errorbar(c, counts, yerr=np.sqrt(counts), xerr=np.diff(RE) / 2, fmt="o", ms=4, label="SYNTHETIC reco counts (mu = 1 injected)")
    ax.stairs(fold_counts, RE, baseline=None, label="QED prediction folded, mu = 1")
    ax.stairs(fold_counts * obs_fit["mu_hat"] * lumi_obs / LUMI, RE, baseline=None, ls="--",
              label=f"fitted mu = {obs_fit['mu_hat']:.3f} (measured luminosity)")
    ax.set_xlabel("reconstructed cos theta"); ax.set_ylabel("events per bin"); ax.set_ylim(bottom=0)
    ax.set_title("SYNTHETIC Path D"); ax.legend(fontsize=7)
    lo, hi = obs_fit["interval_68"]
    grid = np.linspace(lo - 1.5 * (obs_fit["mu_hat"] - lo), hi + 1.5 * (hi - obs_fit["mu_hat"]), 61)
    bx.plot(grid, [obs_fit["q"](m) for m in grid])
    bx.axhline(1.0, ls=":", c="gray"); bx.set_xlabel("mu"); bx.set_ylabel("q(mu)"); bx.set_title("profile likelihood (synthetic)")
    fig.tight_layout(); fig.savefig(out / "folded_comparison.png", dpi=110); plt.close(fig)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--toys", type=int, default=200)
    ap.add_argument("--seed", type=int, default=20261004)
    ap.add_argument("--created", default="2026-10-02")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parent / "output")
    args = ap.parse_args(argv)
    out = args.out
    (out / "artifacts").mkdir(parents=True, exist_ok=True)

    pred_doc = json.loads(PRED_PATH.read_text(encoding="utf-8"))
    comp = compose([EXP, TH], ids=["synthcol:synthetic-path-d-reco-counts", pred_doc["provenance"]["evidence_ids"][0]])
    resp = detector.response(CFG, 1.0, 0.0)  # in-bin weighting 1 + cos^2 theta, the predicted shape
    m = resp["matrix"]
    path_b_m = np.array(json.loads(PATH_B_RESULTS.read_text(encoding="utf-8"))["response"]["matrix"])
    resp_doc = json.loads(PATH_B_RESPONSE.read_text(encoding="utf-8"))

    pred_side = side_from_artifact(pred_doc)
    meas_side = {"artifact_type": "dataset-record", "observable": measurement_observable(), "status": ["synthetic"],
                 "uncertainties": [], "covariance": "absent", "corrections": []}
    p = plan(resp_doc["extension"]["includes"])
    g = gate(pred_side, meas_side, p["transformations"], p["mappings"], p["measurement_conditions"])
    if not g["comparable"]:
        (out / "gate_failure.json").write_text(json.dumps(g, indent=1) + "\n")
        print(json.dumps({"gate": "not comparable; dependent fit stopped", "mismatches": g["mismatches"]}, indent=1))
        return 1

    sigma_bins, fold_counts = folded(pred_doc, m)
    sigma_total = float(sigma_bins.sum())
    quad = quadrature_reference(sigma_total)
    fold_dev = float(np.max(np.abs(fold_counts / quad - 1)))
    r = float(pred_doc["extension"]["values"]["uncertainties"][0]["values"][0] / pred_doc["extension"]["values"]["values"][0])

    asimov = {}
    for mu_inj in (1.0, 1.25):
        fit = Model(mu_inj * fold_counts, fold_counts, LUMI_REL, r).fit()
        asimov[f"{mu_inj:g}"] = {"mu_hat": fit["mu_hat"], "interval_68": fit["interval_68"]}
    free = Model(fold_counts, fold_counts, LUMI_REL, r, constrain=False)
    q_free = 2.0 * (free.profiled(1.15)[0] - free.profiled(1.0)[0])

    rng = np.random.default_rng(args.seed)
    ev = generate_events.generate(CFG, int(rng.integers(2 ** 31)), sigma_pb=1.0 * sigma_total, a=1.0, b=0.0)
    lumi_obs = LUMI * (1.0 + LUMI_REL * rng.normal())
    counts = reco_counts(ev)
    obs_fit = Model(counts, fold_counts * lumi_obs / LUMI, LUMI_REL, r).fit()
    obs_pull = (obs_fit["mu_hat"] - 1.0) / (obs_fit["sigma_minus"] if obs_fit["mu_hat"] > 1 else obs_fit["sigma_plus"])
    toy_res = toys(fold_counts, sigma_total, r, args.toys, args.seed + 1)

    unfolded_side = side_from_artifact(json.loads((PLUGIN / "examples" / "collider-angular" / "output" / "artifacts" / "dataset_record.json").read_text(encoding="utf-8")))
    neg = []
    for v in negative_variants(pred_side, meas_side, p, unfolded_side):
        res = gate(v["prediction"], v["measurement"], v["transformations"], v["mappings"], v["conditions"])
        fields = [x["field"] for x in res["mismatches"]]
        neg.append({"name": v["name"], "expected_field": v["expect_field"], "rejected": not res["comparable"], "expected_field_reported": v["expect_field"] in fields,
                    "mismatches": [{k: x[k] for k in ("field", "reason", "resolve")} for x in res["mismatches"]]})
    conv = positive_conversion(pred_side, unfolded_side, p)

    docs, contract = artifacts(pred_doc, g, fold_counts, r, counts, obs_fit, toy_res, args.created)
    for name, doc in docs.items():
        (out / "artifacts" / f"{name}.json").write_text(json.dumps(doc, indent=1) + "\n")
    n_cov = args.toys
    cov_tol = CRITERIA["coverage_sigma"] * math.sqrt(0.6827 * 0.3173 / n_cov)
    passes = {
        "composition": comp["ok"],
        "gate_comparable": g["comparable"],
        "response_matches_path_b": bool(np.array_equal(m, path_b_m)),
        "fold_vs_quadrature": fold_dev < CRITERIA["fold_vs_quadrature_max_rel_dev"],
        "asimov_injection": all(abs(a["mu_hat"] - float(k)) < CRITERIA["asimov_mu_abs_dev"] for k, a in asimov.items()),
        "identifiable_only_with_constraint": q_free < 1e-6,
        "observed_consistent_with_injected": abs(obs_pull) < CRITERIA["observed_pull_abs"],
        "toy_pulls": all(abs(t["mean_pull"]) < CRITERIA["toy_mean_pull_abs"]
                         and CRITERIA["toy_pull_width"][0] < t["pull_width"] < CRITERIA["toy_pull_width"][1] for t in toy_res.values()),
        "toy_coverage": all(abs(t["coverage_68"] - 0.6827) < cov_tol for t in toy_res.values()),
        "negative_variants_rejected": all(n["rejected"] and n["expected_field_reported"] for n in neg),
        "documented_conversion_accepted": conv["comparable"],
        "contracts": all(c["ok"] for c in contract.values()),
    }
    trace = [{"artifact": d["artifact_id"], "type": d["artifact_type"], "inputs": [i["ref"] for i in d["inputs"]], "status": d["status"]}
             for d in docs.values()]
    results = {
        "label": "SYNTHETIC: data generated at mu = 1 from the illustrative synthetic-collider profile; not a physics result",
        "profiles_loaded": [EXP["id"], TH["id"]], "seed": args.seed, "toys": args.toys, "criteria": CRITERIA, "pass": passes,
        "composition": comp, "gate": {k: v for k, v in g.items() if k != "conventions"} | {"conventions": g["conventions"]},
        "sigma_pred_total_pb": sigma_total, "reference_rounding_rel": r,
        "folded_expectation": fold_counts.tolist(), "quadrature_reference": quad.tolist(), "fold_max_rel_dev": fold_dev,
        "asimov": asimov, "q_without_luminosity_constraint_at_mu_1.15": q_free,
        "observed_synthetic": {"n_generated": ev["meta"]["n_generated"], "reco_counts": counts.tolist(), "luminosity_measured_pb": lumi_obs,
                               "mu_hat": obs_fit["mu_hat"], "interval_68": obs_fit["interval_68"], "plateau_from_kappa": obs_fit["plateau"],
                               "pull_vs_injected": obs_pull},
        "toy_results": toy_res, "coverage_tolerance": cov_tol,
        "negative_variants": neg, "documented_conversion": {"comparable": conv["comparable"], "transformations": conv["transformations"]},
        "contract_trace": trace, "contract_validation": contract,
    }
    (out / "results.json").write_text(json.dumps(results, indent=1, default=float) + "\n")
    figures(counts, fold_counts, obs_fit, lumi_obs, out)
    write_report(out, results)
    digest = hashlib.sha256((out / "results.json").read_bytes()).hexdigest()
    print(json.dumps({"pass": passes, "results_sha256": digest}, indent=1))
    return 0 if all(passes.values()) else 1


