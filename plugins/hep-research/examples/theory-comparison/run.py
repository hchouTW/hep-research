# --- numerics ----------------------------------------------------------------------------------------------------

def folded(pred_doc, resp_matrix):
    v = pred_doc["extension"]["values"]
    width = np.diff(np.array(v["edges"]))
    sigma_bins = np.array(v["values"]) * width          # bin-integrate: pb per truth bin
    return sigma_bins, resp_matrix @ (LUMI * sigma_bins)  # forward-fold expected counts


def quadrature_reference(sigma_total):
    """Independent expected counts per reco bin: integrate L x (3/8) sigma (1 + c^2) x eff(c) x P(reco in bin | c)."""
    e0, e1, s = CFG["efficiency"]["e0"], CFG["efficiency"]["e1"], CFG["resolution"]["sigma_cos"]
    out = []
    for lo, hi in zip(RE[:-1], RE[1:]):
        f = lambda c, lo=lo, hi=hi: LUMI * 0.375 * sigma_total * (1 + c * c) * (e0 - e1 * c ** 4) * (  # noqa: E731
            special.ndtr((hi - c) / s) - special.ndtr((lo - c) / s))
        out.append(integrate.quad(f, -1.0, 1.0, epsabs=0, epsrel=1e-12, limit=200, points=[lo, hi])[0])
    return np.array(out)


class Model:
    """n_k ~ Poisson(mu x kappa x (1 + d theta) x A_k), theta ~ N(0, 1), kappa flat in [1 - r, 1 + r]."""

    def __init__(self, counts, a, d, r, constrain=True):
        self.n, self.a, self.d, self.r, self.constrain = np.asarray(counts, float), np.asarray(a, float), d, r, constrain

    def nll(self, mu, theta, kappa):
        nu = mu * kappa * (1 + self.d * theta) * self.a
        if np.any(nu <= 0):
            return 1e300
        pos = self.n > 0
        val = float(np.sum(nu) - np.sum(self.n[pos] * np.log(nu[pos])))
        return val + (0.5 * theta * theta if self.constrain else 0.0)

    def profiled(self, mu):
        best = None
        for k0 in (1.0, 1 - self.r, 1 + self.r):
            res = optimize.minimize(lambda x: self.nll(mu, x[0], x[1]), x0=[0.0, k0], method="L-BFGS-B",
                                    bounds=[(-10.0, 10.0), (1 - self.r, 1 + self.r)], options={"ftol": 1e-15, "gtol": 1e-12})
            if best is None or res.fun < best.fun:
                best = res
        return best.fun, best

    def fit(self):
        s_hat = float(self.n.sum() / self.a.sum())  # mu x kappa x (1 + d theta) is all the counts identify
        nll0, _ = self.profiled(s_hat)
        q = lambda mu: 2.0 * (self.profiled(mu)[0] - nll0)  # noqa: E731
        guess = s_hat * math.sqrt(1.0 / max(self.n.sum(), 1.0) + self.d ** 2 + self.r ** 2)
        lo = optimize.brentq(lambda m: q(m) - 1.0, s_hat * 0.2, s_hat - 1e-3 * guess, xtol=1e-10)
        hi = optimize.brentq(lambda m: q(m) - 1.0, s_hat + 1e-3 * guess, s_hat * 3.0, xtol=1e-10)
        return {"mu_hat": s_hat, "interval_68": [lo, hi], "sigma_minus": s_hat - lo, "sigma_plus": hi - s_hat,
                "plateau": [s_hat / (1 + self.r), s_hat / (1 - self.r)], "q": q}


def reco_counts(ev):
    sel = ev["selected"] & (ev["reco_cos"] >= RE[0]) & (ev["reco_cos"] < RE[-1])
    return np.histogram(ev["reco_cos"][sel], bins=RE)[0].astype(float)


def toys(fold_counts, sigma_total, r, n_toys, seed):
    out = {}
    for mu_inj in MU_INJECT:
        rng = np.random.default_rng(seed + int(round(mu_inj * 1000)))
        pulls, cover = [], 0
        for i in range(n_toys):
            ev = generate_events.generate(CFG, int(rng.integers(2 ** 31)), sigma_pb=mu_inj * sigma_total, a=1.0, b=0.0)
            lumi_obs = LUMI * (1.0 + LUMI_REL * rng.normal())  # auxiliary luminosity measurement
            fit = Model(reco_counts(ev), fold_counts * lumi_obs / LUMI, LUMI_REL, r).fit()
            lo, hi = fit["interval_68"]
            cover += lo <= mu_inj <= hi
            sig = fit["sigma_plus"] if fit["mu_hat"] < mu_inj else fit["sigma_minus"]
            pulls.append((mu_inj - fit["mu_hat"]) / sig)
        p = np.array(pulls)
        out[f"{mu_inj:g}"] = {"toys": n_toys, "mean_pull": round(float(p.mean()), 4), "pull_width": round(float(p.std(ddof=1)), 4),
                              "coverage_68": round(cover / n_toys, 4)}
    return out


