"""Fast toy configurations of the engine (phase 2): the linear Gaussian and small non-Gaussian configurations on which
Part B states several section 8.7 calibrations and section 15.3 negative tests ("linear Gaussian configuration",
"reduced toy"), labeled `synthetic`. Each is a `fit.py` Problem with a known truth, known MC noise and an
event-level data generator (for Gaussian summary statistics of an analytic model the event-level noise is the
Gaussian of the declared data covariance; Poisson counts are sampled as counts).

A configuration holds:
- theta (d), physical bounds and the prior (sampling) box;
- observables: Gaussian rows m(theta) = m0 + J theta + quad(theta) (identity link), optional count-type data errors
  V_data(theta) = V_data + c diag(m(theta)) (they make V depend on theta, so the section 7.3 iteration has work);
- nu columns U and eta columns S (link space, N(0, 1) constraints);
- MC noise of the nominal prediction e_nom ~ N(0, V_MC), optionally varying with theta (e_nom(theta) = e0 + theta e1,
  the Jacobian MC noise of section 8.2 note 3);
- N_d,c constraint vectors;
- optional Poisson count shape with BB-lite (absolute counts, mu_k(theta) = a_k exp(b_k theta_0)).
"""
from __future__ import annotations

import math
from dataclasses import dataclass, field

import numpy as np

from . import likelihood as L


def F_seed(seed):
    if isinstance(seed, (tuple, list)):
        return int(np.random.SeedSequence([int(s) for s in seed]).generate_state(1)[0])
    return int(seed)


@dataclass
class Config:
    J: np.ndarray                                  # n x d
    m0: np.ndarray                                 # n
    V_data: np.ndarray                             # n x n (at theta = 0 when count-type)
    V_MC: np.ndarray                               # n x n
    bounds: list                                   # physical (lo, hi) per theta
    prior: list                                    # sampling box (lo, hi) per theta
    U: np.ndarray | None = None                    # nu columns
    S: np.ndarray | None = None                    # eta columns
    quad: np.ndarray | None = None                 # n x d x d second-order coefficients (nonlinearity)
    count_c: float = 0.0                           # V_data(theta) = V_data + count_c * diag(m(theta) - m0)
    e1: np.ndarray | None = None                   # n x d: Jacobian MC noise scale (e_nom(theta) = e0 + e1 theta)
    constraints: list = field(default_factory=list)
    poisson: dict | None = None                    # {a: K, b: K, tau: K}
    names: list | None = None
    bimodal: bool = False                          # m depends on (theta0 - c)^2: two mirror basins
    phi_cols: np.ndarray | None = None             # n x q: linear response to shift-mode phi (unit-normal units)
    phi_resp: object = None                        # callable(phi[, tp]) -> n-vector: nonlinear part of the response
    degeneracy_modes: list = field(default_factory=list)
    val: dict | None = None                        # validation rows: {J, m0, V_data, V_MC, U, S, constraints,
                                                   #  phi_cols} (identity link)
    bootstrap_B: int = 0                           # > 0: V_data is estimated by an event-level bootstrap of B sets
    e_scale: np.ndarray | None = None              # n x d: e_nom(theta) = e0 * (1 + e_scale theta) (K_l != 0)


class LinearProblem:
    """A fit.py Problem over a Config with one realization of the nominal MC noise (seed `mc_seed`) and observed
    data `data` (generated by `simulate`)."""

    def __init__(self, cfg: Config, mc_seed: int = 1, data: L.Data | None = None, truth=None, mc_scale=1.0):
        self.cfg = cfg
        n, d = cfg.J.shape
        self.d = d
        self.theta_names = [f"t{i}" for i in range(d)]
        obs = [{"name": f"y{i}", "block": "gaussian", "link": "identity"} for i in range(n)]
        if cfg.poisson is not None:
            obs.append({"name": "counts", "block": "poisson", "bins": len(cfg.poisson["a"]), "free_omega": False,
                        "bb": True})
        n_nu = 0 if cfg.U is None else cfg.U.shape[1]
        n_eta = 0 if cfg.S is None else cfg.S.shape[1]
        self.layout = L.build_layout(obs, self.theta_names, [], n_nu, n_eta)
        rng = np.random.default_rng(mc_seed)
        self.e0 = rng.multivariate_normal(np.zeros(n), cfg.V_MC) * mc_scale if cfg.V_MC.any() else np.zeros(n)
        self.e1n = (rng.normal(size=(n, d)) * cfg.e1) if cfg.e1 is not None else None
        self.pert = np.zeros(self.layout.n_link)
        self.sigma_noise = 0.0
        self.edm_tol = 0.01
        self.data = data
        self.truth = truth
        self.boot_seed = (mc_seed, 1)
        self.V_depends_on_theta = cfg.count_c > 0
        self.shift_names = [f"phi{l}" for l in range(cfg.phi_cols.shape[1])] if cfg.phi_cols is not None else []
        self.degeneracy_modes = list(cfg.degeneracy_modes)
        if cfg.poisson is not None:
            K = len(cfg.poisson["a"])
            self.tau = np.asarray(cfg.poisson["tau"], float)
            # the MC estimate of the counts carries Poisson(tau) noise: f_k = m_k / tau_k
            self.mc_f = rng.poisson(self.tau) / np.where(self.tau > 0, self.tau, 1.0)
        else:
            self.tau, self.mc_f = None, None

    # -- model
    def mean(self, theta):
        c = self.cfg
        t = np.asarray(theta, float)
        m = c.m0 + c.J @ (t if not c.bimodal else np.r_[(t[0] - 1.0) ** 2, t[1:]])
        if c.quad is not None:
            m = m + np.einsum("nij,i,j->n", c.quad, t, t)
        return m

    def mc_noise(self, theta):
        e = self.e0.copy()
        if self.cfg.e_scale is not None:
            e = e * (1.0 + self.cfg.e_scale @ np.asarray(theta, float))
        if self.e1n is not None:
            e = e + self.e1n @ np.asarray(theta, float)
        return e

    def counts_mean(self, theta):
        p = self.cfg.poisson
        return np.asarray(p["a"], float) * np.exp(np.asarray(p["b"], float) * float(theta[0]))

    def h(self, tp):
        """The link-space nominal-MC predictor (with its MC noise) plus a toy's perturbation."""
        g = self.mean(tp) + self.mc_noise(tp)
        if self.cfg.poisson is not None:
            g = np.r_[g, np.log(self.counts_mean(tp) * self.mc_f_or_one())]
        return g + self.pert

    def h_shift(self, tp, phis):
        """The predictor with the shift-mode phi at `phis` (unit-normal coordinates)."""
        g = self.h(tp)
        n = self.cfg.J.shape[0]
        phis = np.asarray(phis, float)
        g[:n] = g[:n] + self.cfg.phi_cols @ phis
        if self.cfg.phi_resp is not None:
            try:
                g[:n] = g[:n] + self.cfg.phi_resp(phis, np.asarray(tp, float))
            except TypeError:
                g[:n] = g[:n] + self.cfg.phi_resp(phis)
        return g

    # -- validation rows (holdout)
    def h_val(self, tp, phis=None):
        v = self.cfg.val
        g = v["m0"] + v["J"] @ np.asarray(tp, float)[:self.d] + self.val_noise
        if phis is not None and v.get("phi_cols") is not None:
            g = g + v["phi_cols"] @ np.asarray(phis, float)
        return g + self.val_pert

    @property
    def val_noise(self):
        if not hasattr(self, "_val_noise"):
            v = self.cfg.val
            r = np.random.default_rng([self.mc_seed, 77])
            self._val_noise = r.multivariate_normal(np.zeros(len(v["m0"])), v["V_MC"]) if np.any(v["V_MC"]) \
                else np.zeros(len(v["m0"]))
        return self._val_noise

    val_pert = 0.0

    def val_columns(self):
        v = self.cfg.val
        nv = len(v["m0"])
        U = v.get("U") if v.get("U") is not None else np.zeros((nv, self.layout.n_nu))
        S = v.get("S") if v.get("S") is not None else np.zeros((nv, self.layout.n_eta))
        return U, S

    def simulate_val(self, beta_truth, rng, phis=None):
        v = self.cfg.val
        sl = self.layout.slices()
        U, S = self.val_columns()
        mu = v["m0"] + v["J"] @ beta_truth[:self.d] + U @ beta_truth[sl["nu"]] + S @ beta_truth[sl["eta"]]
        if phis is not None and v.get("phi_cols") is not None:
            mu = mu + v["phi_cols"] @ np.asarray(phis, float)
        return rng.multivariate_normal(mu, v["V_data"])

    def mc_f_or_one(self):
        return np.where(self.tau > 0, self.mc_f, 1.0) if self.mc_f is not None else 1.0

    def V_data_at(self, theta):
        c = self.cfg
        V = c.V_data.copy()
        if c.count_c > 0:
            V = V + c.count_c * np.diag(np.maximum(self.mean(theta), 1e-3))
        return V

    @property
    def has_bootstrap(self):
        return self.cfg.bootstrap_B > 0

    def bootstrap_vhat(self, tp, seed) -> np.ndarray:
        """One bootstrap realization of V_data at theta_ref: the sample covariance of B sets of the summary statistics
        generated from the model at theta_ref with common random numbers (the same uniforms at every theta_ref,
        section 2.1 (i)); never resampled from the observed data."""
        V = self.V_data_at(tp)
        n = V.shape[0]
        B = max(self.cfg.bootstrap_B, L.bootstrap_size(n))
        z = np.random.default_rng([F_seed(seed), 4242]).normal(size=(B, n))
        X = z @ np.linalg.cholesky(V).T
        return L.bootstrap_covariance(X)

    def reference(self, tp, beta, frozen=None, bootstrap_frozen=False, bootstrap_seed=None):
        c = self.cfg
        if frozen is not None and self.has_bootstrap:
            Vd = frozen.V_std
        elif self.has_bootstrap:
            Vd = self.bootstrap_vhat(tp, self.boot_seed if bootstrap_seed is None else bootstrap_seed)
        else:
            Vd = self.V_data_at(tp)
        n = c.J.shape[0]
        U = np.zeros((self.layout.n_link, self.layout.n_nu))
        S = np.zeros((self.layout.n_link, self.layout.n_eta))
        if c.U is not None:
            U[:n] = c.U
        if c.S is not None:
            S[:n] = c.S
        tau = {"counts": self.tau * self.mc_f_or_one()} if c.poisson is not None else {}
        return L.Reference(V_G=Vd + c.V_MC, V_std=Vd, U=U, S=S, tau=tau, constraints=list(c.constraints)).finalize()

    def bounds(self):
        return list(self.cfg.bounds)

    def prior_box(self):
        return list(self.cfg.prior)

    def sigma_prior(self):
        return [(hi - lo) / math.sqrt(12.0) for lo, hi in self.cfg.prior]

    @property
    def V_MC_link(self):
        n = self.cfg.J.shape[0]
        V = np.zeros((n, n))
        V[:] = self.cfg.V_MC
        return V

    # -- toys
    def simulate(self, beta_truth: np.ndarray, rng: np.random.Generator, phis=None) -> L.Data:
        """Event-level data at the truth (Gaussian rows with the data covariance at the truth, counts as Poisson), the
        constraint centres of nu and eta sampled around their true values (the profile construction, section 6.6).
        The truth carries no MC noise (the analytic truth of section 8.7 note 4)."""
        c = self.cfg
        lay = self.layout
        sl = lay.slices()
        d = self.d
        th = beta_truth[:d]
        nu = beta_truth[sl["nu"]]
        eta = beta_truth[sl["eta"]]
        mu = self.mean(th)
        n = c.J.shape[0]
        if c.U is not None:
            mu = mu + c.U @ nu
        if c.S is not None:
            mu = mu + c.S @ eta
        if phis is not None and c.phi_cols is not None:
            mu = mu + c.phi_cols @ np.asarray(phis, float)
            if c.phi_resp is not None:
                try:
                    mu = mu + c.phi_resp(np.asarray(phis, float), np.asarray(th, float))
                except TypeError:
                    mu = mu + c.phi_resp(np.asarray(phis, float))
        y = rng.multivariate_normal(mu, self.V_data_at(th))
        out = L.Data(y_gauss=y, nu0=rng.normal(nu, 1.0) if lay.n_nu else None,
                     eta0=rng.normal(eta, 1.0) if lay.n_eta else None)
        if c.poisson is not None:
            g = beta_truth[sl["gamma"]] if lay.gamma else 1.0
            out.counts = {"counts": rng.poisson(self.counts_mean(th) * g)}
            out.aux_m = {"counts": rng.poisson(self.tau * g)}
        return out

    def replica_pert(self, rng: np.random.Generator, theta=None) -> np.ndarray:
        """(m_a - m_b) / sqrt(2) of two independent replicas at the generation point (section 6.6): covariance V_MC."""
        n = self.cfg.J.shape[0]
        out = np.zeros(self.layout.n_link)
        if self.cfg.V_MC.any():
            a = rng.multivariate_normal(np.zeros(n), self.cfg.V_MC)
            b = rng.multivariate_normal(np.zeros(n), self.cfg.V_MC)
            out[:n] = (a - b) / math.sqrt(2.0)
        return out

    def replica_pert_val(self, rng: np.random.Generator) -> np.ndarray:
        v = self.cfg.val
        nv = len(v["m0"])
        if not np.any(v["V_MC"]):
            return np.zeros(nv)
        a = rng.multivariate_normal(np.zeros(nv), v["V_MC"])
        b = rng.multivariate_normal(np.zeros(nv), v["V_MC"])
        return (a - b) / math.sqrt(2.0)

    def subset(self, rows) -> "LinearProblem":
        """The problem restricted to the Gaussian calibration rows `rows` (a training fold, section 9.3): same truth,
        MC noise and data on those rows."""
        rows = np.asarray(rows, int)
        c = self.cfg
        sub = Config(c.J[rows], c.m0[rows], c.V_data[np.ix_(rows, rows)], c.V_MC[np.ix_(rows, rows)], c.bounds,
                     c.prior, None if c.U is None else c.U[rows], None if c.S is None else c.S[rows],
                     None if c.quad is None else c.quad[rows], c.count_c, None if c.e1 is None else c.e1[rows],
                     [np.asarray(v)[rows] for v in c.constraints if np.all(np.asarray(v)[np.setdiff1d(
                         np.arange(len(c.m0)), rows)] == 0)], None, None, c.bimodal,
                     None if c.phi_cols is None else c.phi_cols[rows], None, list(c.degeneracy_modes))
        p = LinearProblem(sub, self.mc_seed)
        p._mc_seed = self.mc_seed
        p.e0 = self.e0[rows]
        p.e1n = None if self.e1n is None else self.e1n[rows]
        if self.data is not None:
            p.data = L.Data(y_gauss=self.data.y_gauss[rows], nu0=self.data.nu0, eta0=self.data.eta0)
        p.pert = self.pert[rows] if np.ndim(self.pert) else self.pert
        p.truth = self.truth
        return p

    def with_data(self, data: L.Data, mc_seed=None):
        p = LinearProblem(self.cfg, self.mc_seed if mc_seed is None else mc_seed, data, self.truth)
        return p

    @property
    def mc_seed(self):
        return getattr(self, "_mc_seed", 1)


def make(cfg: Config, truth_theta, data_seed: int, mc_seed: int, nu=None, eta=None) -> LinearProblem:
    """A problem with data simulated at the truth (nu, eta default 0)."""
    p = LinearProblem(cfg, mc_seed)
    p._mc_seed = mc_seed
    lay = p.layout
    beta = np.zeros(lay.n_beta)
    sl = lay.slices()
    beta[:p.d] = truth_theta
    if lay.n_nu:
        beta[sl["nu"]] = 0.0 if nu is None else nu
    if lay.n_eta:
        beta[sl["eta"]] = 0.0 if eta is None else eta
    beta[sl["gamma"]] = 1.0
    p.data = p.simulate(beta, np.random.default_rng(data_seed))
    p.truth = beta
    return p


def linear_config(n=20, d=3, seed=0, sd=1.0, mc_ratio=0.0, n_nu=0, n_eta=0, count_c=0.0, quad=None,
                  e1=None, constraints=None, poisson=None, bounds=None, prior=None, corr_mc=False) -> Config:
    """A random linear Gaussian configuration: J ~ N(0, 1), V_data = sd^2 I, V_MC = mc_ratio V_data (or a correlated
    matrix with the same trace when corr_mc)."""
    rng = np.random.default_rng(seed)
    J = rng.normal(size=(n, d))
    Vd = np.eye(n) * sd ** 2
    if corr_mc:
        A = rng.normal(size=(n, n))
        C = A @ A.T
        Vm = C / np.trace(C) * np.trace(Vd) * mc_ratio
    else:
        Vm = Vd * mc_ratio
    U = rng.normal(size=(n, n_nu)) * 0.3 if n_nu else None
    S = rng.normal(size=(n, n_eta)) * 0.3 if n_eta else None
    b = bounds or [(-10.0, 10.0)] * d
    pr = prior or [(-3.0, 3.0)] * d
    return Config(J, np.full(n, 10.0), Vd, Vm, b, pr, U, S, quad, count_c, e1, list(constraints or []), poisson)


def initial_beta(p: LinearProblem, theta0=None) -> np.ndarray:
    lk = L.Likelihood(p.layout, p.data, p.reference(np.zeros(p.d), None))
    b = lk.initial_beta(dict(zip(p.theta_names, np.zeros(p.d) if theta0 is None else theta0)))
    return b
