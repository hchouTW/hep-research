def exact_quadratic(xs, ys, nodes_, x) -> Fraction:
    """The quadratic through three nodes at x, in exact rational arithmetic (hand-computed Newton form)."""
    (x0, y0), (x1, y1), (x2, y2) = ((Fraction(xs[k]), Fraction(ys[k])) for k in nodes_)
    d1 = (y1 - y0) / (x1 - x0)
    d2 = ((y2 - y1) / (x2 - x1) - d1) / (x2 - x0)
    return y0 + (Fraction(x) - x0) * d1 + (Fraction(x) - x0) * (Fraction(x) - x1) * d2


class Reimplementation(unittest.TestCase):
    def setUp(self):
        table = parsed()
        self.xs, self.ys = garfield.node_fields(table), garfield.node_velocities(table)
        self.settings = {"order": 2, "low": "constant", "high": "linear"}

    def reference(self, x):
        n = len(self.xs)
        ix = garfield.last_node_at_or_below(self.xs, x)
        if ix == 1:
            return exact_quadratic(self.xs, self.ys, (0, 1, 2), x)
        if ix == n - 1:
            return exact_quadratic(self.xs, self.ys, (n - 3, n - 2, n - 1), x)
        return (exact_quadratic(self.xs, self.ys, (ix - 2, ix - 1, ix), x)
                + exact_quadratic(self.xs, self.ys, (ix - 1, ix, ix + 1), x)) / 2

    def test_pinned_stencil_against_exact_arithmetic(self):
        for x in (160.0, 200.0, 500.0, 1100.0, 3000.0, 6000.0, 7000.0):  # ix = 1, 1, 2, 3, 4, 5, 5
            with self.subTest(x=x):
                r = float(self.reference(x))
                self.assertTrue(garfield.within_tolerance(garfield.divdif_order2(self.xs, self.ys, x), r, "interior"))

    def test_a_quadratic_is_reproduced_by_every_stencil(self):
        ys = [0.5 + 0.002 * x - 1e-7 * x * x for x in self.xs]
        for x in (200.0, 1100.0, 6000.0):
            exact = Fraction(0.5) + Fraction(0.002) * Fraction(x) - Fraction(1e-7) * Fraction(x) ** 2
            with self.subTest(x=x):
                self.assertAlmostEqual(garfield.divdif_order2(self.xs, ys, x), float(exact), delta=1e-12)

    def test_a_different_stencil_fails_check_3(self):
        # the table is a cubic: inside the table the single quadratic through (ix-1, ix, ix+1) differs from the
        # pinned average by O(h^3 f''') and must fail the check-3 tolerance; the pinned rule passes
        x = 1100.0  # ix = 3 (between nodes 3 and 4 of 6), both neighbouring quadratics exist
        pinned = garfield.divdif_order2(self.xs, self.ys, x)
        other = float(exact_quadratic(self.xs, self.ys, (1, 2, 3), x))
        self.assertTrue(garfield.within_tolerance(pinned, float(self.reference(x)), "interior"))
        self.assertFalse(garfield.within_tolerance(other, pinned, "interior"))
        next_to_end = float(exact_quadratic(self.xs, self.ys, (1, 2, 3), 200.0))  # ix = 1 must use nodes 1, 2, 3
        self.assertFalse(garfield.within_tolerance(next_to_end, garfield.divdif_order2(self.xs, self.ys, 200.0),
                                                   "interior"))

    def test_nodes_and_end_rule(self):
        for k, x in enumerate(self.xs):
            with self.subTest(node=k):
                self.assertEqual(garfield.divdif_order2(self.xs, self.ys, x), self.ys[k])
                self.assertEqual(garfield.reference_velocity(self.xs, self.ys, x, self.settings), (self.ys[k], "node"))
        near_end = self.xs[-1] - 1e-7 * (self.xs[-1] - self.xs[-2])  # within 1e-6 of the end spacing
        self.assertEqual(garfield.divdif_order2(self.xs, self.ys, near_end), self.ys[-1])

    def test_linear_interpolation_and_extrapolation(self):
        x0, x1, y0, y1 = self.xs[1], self.xs[2], self.ys[1], self.ys[2]
        f = (500.0 - x0) / (x1 - x0)
        self.assertEqual(garfield.linear_interpolation(self.xs, self.ys, 500.0), y0 * (1 - f) + f * y1)
        self.assertEqual(garfield.extrapolate(self.xs, self.ys, 50.0, "constant", "low"), self.ys[0])
        slope = (self.ys[-1] - self.ys[-2]) / (self.xs[-1] - self.xs[-2])
        self.assertEqual(garfield.extrapolate(self.xs, self.ys, 9000.0, "linear", "high"),
                         self.ys[-1] + slope * (9000.0 - self.xs[-1]))
        exp = garfield.extrapolate(self.xs, self.ys, 9000.0, "exponential", "high")
        b = (math.log(self.ys[-2]) - math.log(self.ys[-1])) / (self.xs[-2] - self.xs[-1])
        self.assertAlmostEqual(exp, self.ys[-1] * math.exp(b * (9000.0 - self.xs[-1])), delta=1e-15)
        self.assertEqual(garfield.reference_velocity(self.xs, self.ys, 50.0, self.settings)[1], "below")
        self.assertEqual(garfield.reference_velocity(self.xs, self.ys, 9000.0, self.settings)[1], "above")

    def test_tolerances(self):
        t = 3.4219876e-4
        self.assertTrue(garfield.within_tolerance(t + 4 * math.ulp(t), t, "node"))
        self.assertFalse(garfield.within_tolerance(t + 5 * math.ulp(t), t, "node"))
        self.assertTrue(garfield.within_tolerance(t * (1 + 0.9e-12), t, "interior"))
        self.assertFalse(garfield.within_tolerance(t * (1 + 2e-12), t, "interior"))
        self.assertFalse(garfield.within_tolerance(float("nan"), t, "interior"))


