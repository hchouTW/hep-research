def simulated_output(query: dict, table: dict, mutate=None) -> str:
    """What a correct query script writes, computed with Garfield++'s B = 0 formula from the reimplementation:
    v = (q ve / |E|) E with q = -1 and E = (E, 0, 0). mutate(index, [vx, vy, vz, |v|]) may corrupt values."""
    xs, ys = garfield.node_fields(table), garfield.node_velocities(table)
    lines = ["format " + garfield.OUTPUT_FORMAT, "pressure_torr " + repr(table["pressure_torr"]),
             "temperature_k " + repr(table["temperature_k"]),
             "interpolation {order} {low} {high}".format(**query["interpolation"])]
    for point in query["points"]:
        e = float(point["field_v_per_cm"])
        ve = garfield.reference_velocity(xs, ys, e, query["interpolation"])[0]
        mu = -1.0 * ve / e
        values = [mu * e, mu * 0.0, mu * 0.0]
        values.append(math.sqrt(sum(v * v for v in values)))
        if mutate is not None:
            values = mutate(point["index"], values)
            if values is None:
                continue
        lines.append(f"point {point['index']} {point['field_v_per_cm']} {' '.join(map(repr, values))}")
    lines.append(f"end {len(query['points'])}")
    return "\n".join(lines) + "\n"


