        self.assert_issue(self.project(name="p2", pressure={"value": "750", "unit": "Torr"}), "condition-mismatch",
                          "refused")
        self.assertEqual(self.checked(self.project(name="p3", pressure={"value": "7.6e2", "unit": "Torr"})), [])

