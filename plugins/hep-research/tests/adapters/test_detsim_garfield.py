def task_document(env_identity: str, fields=None, table_path: str = "inputs/syn table.gas", **overrides) -> dict:
    parameters = {"table_role": "gas_table",
                  "query_fields": [{"value": v, "unit": "V/cm"} for v in (fields or default_fields())],
                  "magnetic_field": {"value": "0", "unit": "T"}, "temperature": {"value": "300", "unit": "K"},
                  "pressure": {"value": "760", "unit": "Torr"},
                  "interpolation": {"order": 2, "low": "constant", "high": "linear"}}
    parameters.update(overrides)
    return {"schema": "detector-task/1", "capability_id": "garfield.gas-table-query",
            "objective": "synthetic GF-QUERY test (synthetic table, no physics)", "environment_ref": env_identity,
            "inputs": [{"role": "gas_table", "path": table_path}], "parameters": parameters,
            "budget": {"timeout_s": 60, "max_output_bytes": 1048576}}


