# ------------------------------------------------------------------ the post-hoc fixture as a fit problem
def posthoc_model(n: int, spec: dict):
    """toy.Model of the post-hoc fixture's chain with n events per run, plus two validation observables that the
    correction moves differently: the fraction with y > 1 and the mean of y^2."""
    s = copy.deepcopy(spec)
    for r in s["runs"]:
        r["n"] = int(n)
    m = toy.chain_from_spec(s, {}).model
    m.observables += [toy.Observable("y_hi", "run", lambda ev: ev["correction"]["y"] > 1.0, "fraction"),
                      toy.Observable("y_sq", "run", lambda ev: ev["correction"]["y"] ** 2, "mean")]
    return m


def posthoc_problem(exposure: int = 2000, mc_events: int = 10_000, mc_seed=20261541, validation: bool = True,
                    generation: dict | None = None, learned: dict | None = None, val_mc_seed=20261542,
                    boot_seed=20261543) -> ToyProblem:
    """The ToyProblem of the post-hoc fixture (core/calibration/data/toy_posthoc.json): theta = strength (prior and
    bounds 0.0005 inside the support [0, 0.2]), calibration y_mean, y_width, holdout validation y_hi, y_sq on an independent sample.
    learned: overrides of plan.evaluator.learned; None as the key `learned` removes it (the plan then has no learned
    ratio: strength is evaluated by resimulation of the black box, the default-off control)."""
    _, plan = toy.posthoc_fixture()
    plan = copy.deepcopy(plan)
    if learned is not None and learned.get("learned", True) is None:
        plan["evaluator"].pop("learned")
        plan["methods"] = {"strength": "resimulation"}
    elif learned:
        plan["evaluator"]["learned"].update(learned)
    spec = plan["evaluator"]["spec"]
    # bounds inside the support by > 2 finite-difference steps (the ratio is refused outside its training box)
    return ToyProblem(lambda n: posthoc_model(n, spec), CALIBRATION, {"strength": {"bounds": (0.0005, 0.1995),
                      "prior": (0.0, 0.2)}}, exposure, mc_events, mc_seed=mc_seed, links=LINKS, plan=plan,
                      boot_seed=boot_seed, generation=generation, val_names=VALIDATION if validation else None,
                      val_mc_seed=val_mc_seed)


def true_values(c: float) -> dict:
    """The true simulator's expectations at strength c (y = x + c x^2 + 0.5 eps, x, eps ~ N(0, 1)): mean c, width
    sqrt(1.25 + 2 c^2), mean of y^2 1.25 + 3 c^2, P(y > 1) by quadrature. Observable units (no MC noise)."""
    from scipy import integrate, stats
    hi = integrate.quad(lambda x: stats.norm.pdf(x) * stats.norm.sf((1.0 - x - c * x * x) / 0.5), -12, 12,
                        epsabs=1e-13, limit=200)[0]
    return {"y_mean": c, "y_width": math.sqrt(1.25 + 2 * c * c), "y_sq": 1.25 + 3 * c * c, "y_hi": hi}


def true_link(c: float, names) -> np.ndarray:
    from core.calibration import likelihood as L
    t = true_values(c)
    return np.array([L.link(np.array([t[n]]), LINKS[n])[0] for n in names])


def prediction_error(problem: ToyProblem, c: float, validation: bool = False) -> dict:
    """The nominal prediction's error at the truth c in link space (MC noise plus the classifier's error), with the
    covariance the likelihood assigns to it: V_MC and V_learn (section 2.1; validation: section 9.2)."""
    p = {"strength": c}
    if validation:
        r = problem._val_predict(p)
        g = problem._val_dlink(r["pred"])
        e = problem._val_link(r["pred"]) - true_link(c, problem.val_names)
    else:
        r = problem._predict(p)
        g = problem._dlink(r["pred"])
        e = problem._to_link(r["pred"]) - true_link(c, problem.names)
    return {"e": e, "V_MC": r["V_MC"] * np.outer(g, g), **problem.v_learn_link(p, validation)}


# ------------------------------------------------------------------ S4: one reference toy, one actual repetition
def _seed(j: int, i: int, k: int = 0) -> int:
    return int(np.random.SeedSequence([SEED0, j, i, k]).generate_state(1)[0] % (2 ** 31 - 1)) + 1


def nominal_problem(config: dict | None = None):
    """The nominal problem of the reference toys and its section 7.3 fit on true-simulator data at the truth; C_r^+
    of that fit (the toys' T_v uses it, section 9.2)."""
    cfg = {**CONFIG, **(config or {})}
    pr = posthoc_problem(cfg["exposure"], cfg["mc_events"], _seed(0, 0, 1), generation={"strength": TRUTH},
                         learned={"degree": cfg["degree"]}, val_mc_seed=_seed(0, 0, 2), boot_seed=_seed(0, 0, 3))
    rng = np.random.default_rng(_seed(0, 0, 4))
    truth = np.array([TRUTH])
    obs = pr.simulate(truth, rng, nominal=False)
    yv = pr.simulate_val(truth, rng, nominal=False)
    p = pr.with_data(obs)
    f = F.iterate(p, truth)
    if not f.converged:
        raise RuntimeError(f"the nominal fit of S4 did not converge: {f.reason}")
    p.set_val_point(f.beta[:1])
    pc = V.holdout_pieces(p, f, yv)
    Cp, k = V.c_r_plus(pc["C_r"], pc["s"], pc["constraints"])
    return p, f, Cp, k


def reference_toy(nominal, i: int) -> dict:
    """Reference toy i in both constructions: the learned path (replicas retrained, N(0, V_learn^bias) drawn) and the
    control without either (`no-learned-toys`). Truth: the known truth (as note 4's calibration 12)."""
    p, f, Cp, _ = nominal
    out: dict = {"i": i}
    for name, omit in (("learned", ()), ("no-learned-toys", ("bias_draw", "retrain"))):
        p.learned_omit = omit
        rng = np.random.default_rng(_seed(1, i, 0 if name == "learned" else 1))
        try:
            ok, r, _ = V.holdout_toy(p, f, np.array([TRUTH]), rng, n_start=0)
        except (ValueError, np.linalg.LinAlgError):           # e.g. learned.outside_support: a failed toy fit
            ok, r = False, None
        out[name] = V.t_v(r, Cp) if ok else None
    p.learned_omit = ()
    return out


def actual_repetition(i: int, config: dict | None = None) -> dict:
    """Actual repetition i: its own nominal MC, classifiers and bootstrap; true-simulator data at the truth; the
    section 7.3 fit; T_v with its own C_r^+ (and, reported only, with V_learn left out of C_r and the chi2_k p)."""
    from scipy import stats
    cfg = {**CONFIG, **(config or {})}
    pr = posthoc_problem(cfg["exposure"], cfg["mc_events"], _seed(2, i, 1), generation={"strength": TRUTH},
                         learned={"degree": cfg["degree"]}, val_mc_seed=_seed(2, i, 2), boot_seed=_seed(2, i, 3))
    rng = np.random.default_rng(_seed(2, i, 4))
    truth = np.array([TRUTH])
    p = pr.with_data(pr.simulate(truth, rng, nominal=False))
    yv = pr.simulate_val(truth, rng, nominal=False)
    try:
        f = F.iterate(p, truth)
    except (ValueError, np.linalg.LinAlgError) as exc:     # e.g. learned.outside_support: reported, not rejected
        return {"i": i, "status": "nonconverged", "reason": repr(exc)}
    if not f.converged:
        return {"i": i, "status": "nonconverged", "reason": f.reason}
    p.set_val_point(f.beta[:1])
    row: dict = {"i": i, "status": "ok", "theta": float(f.beta[0])}
    for name, omit in (("T", ()), ("T_without_V_learn", ("learn",))):
        pc = V.holdout_pieces(p, f, yv, omit=omit)
        Cp, k = V.c_r_plus(pc["C_r"], pc["s"], pc["constraints"])
        row[name] = V.t_v(pc["r"], Cp)
        row["k"] = k
    row["p_chi2"] = float(stats.chi2.sf(row["T"], row["k"]))
    return row


# ------------------------------------------------------------------ tasks, merge, decision
def provenance() -> dict:
    try:
        commit = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True, check=True,
                                timeout=60).stdout.strip()
        dirty = bool(subprocess.run(["git", "status", "--porcelain", "--", *FILES], cwd=ROOT, capture_output=True,
                                    text=True, timeout=60).stdout.strip())
    except (OSError, subprocess.CalledProcessError, subprocess.TimeoutExpired):
        commit, dirty = None, None
    return {"commit": commit, "dirty": dirty, "python": sys.version.split()[0], "numpy": np.__version__,
            "sha256": {f: hashlib.sha256((ROOT / f).read_bytes()).hexdigest() for f in FILES if (ROOT / f).exists()}}


def run_task(i: int, out_dir: Path, tasks=None, config: dict | None = None) -> dict:
    kw = (tasks or TASKS)[i]
    t0 = time.time()
    rows: list = []
    try:
        if kw["kind"] == "reference":
            nom = nominal_problem(config)
            rows = [reference_toy(nom, j) for j in range(kw["i0"], kw["i0"] + kw["n"])]
        else:
            rows = [actual_repetition(j, config) for j in range(kw["i0"], kw["i0"] + kw["n"])]
        status = "ok"
    except Exception as exc:                       # recorded, never counted as passing
        status = f"error: {exc!r}"
    rec = {"task": i, "kwargs": kw, "config": {**CONFIG, **(config or {})}, "status": status, "rows": rows,
           "seconds": time.time() - t0, "provenance": provenance(), "flags": FLAGS}
    out_dir.mkdir(parents=True, exist_ok=True)
    io.write_json(str(out_dir / f"task_{i:04d}.json"), io.jsonable(rec))
    return rec


def pvalue(T_obs: float, ref) -> float:
    """(#{T_ref >= T_obs} + 1) / (n + 1); a non-converged reference toy counts as T >= T_obs (section 7.3)."""
    ref = list(ref)
    X = sum(1 for t in ref if t is None)
    T = np.asarray([t for t in ref if t is not None], float)
    return float((np.sum(T >= T_obs) + X + 1) / (len(ref) + 1))


def judge(ref_rows: list, rows: list, reps: int = REPS, n_ref: int = N_REF, alpha: float = ALPHA_TV) -> dict:
    """The registered rule (section 8.7 note 4, line 2063): the rejection rate of the learned-path toy-calibrated T_v
    is within alpha +- 25%, over `reps` repetitions against `n_ref` reference toys. A non-converged actual fit is
    reported and enters the rate as not rejected; the result is incomplete if any repetition or toy is missing.
    Reported, not judged: the `no-learned-toys` reference, V_learn left out of C_r, and the chi2_k p."""
    ref = {k: [r[k] for r in ref_rows] for k in ("learned", "no-learned-toys")}
    ok = [r for r in rows if r.get("status") == "ok"]
    rate = {k: float(np.mean([pvalue(r["T"], v) <= alpha for r in ok])) if ok else None for k, v in ref.items()}
    rate["learned|without_V_learn_in_C_r"] = float(np.mean([pvalue(r["T_without_V_learn"], ref["learned"]) <= alpha
                                                         for r in ok])) if ok else None
    rate["chi2_k"] = float(np.mean([r["p_chi2"] <= alpha for r in ok])) if ok else None
    complete = len({r["i"] for r in rows}) == reps and len({r["i"] for r in ref_rows}) == n_ref
    size = rate["learned"]
    passed = bool(complete and size is not None and abs(size - alpha) <= 0.25 * alpha)
    return {"rate": rate, "alpha": alpha, "band": [0.75 * alpha, 1.25 * alpha], "repetitions": len(rows),
            "nonconverged": len(rows) - len(ok), "reference_toys": len(ref_rows),
            "reference_nonconverged": {k: sum(t is None for t in v) for k, v in ref.items()}, "complete": complete,
            "passed": passed, "flags": FLAGS}


def merge(out_dir: Path, out: Path, tasks=None, reps: int = REPS, n_ref: int = N_REF) -> dict:
    tasks = tasks or TASKS
    recs = {}
    for i in range(len(tasks)):
        f = out_dir / f"task_{i:04d}.json"
        recs[i] = json.loads(f.read_text()) if f.exists() else None
    missing = [i for i, r in recs.items() if r is None]
    errors = [i for i, r in recs.items() if r and r["status"] != "ok"]
    commits = {r["provenance"]["commit"] for r in recs.values() if r}
    dirty = any(r["provenance"].get("dirty") for r in recs.values() if r)
    ref_rows = [row for r in recs.values() if r and r["kwargs"]["kind"] == "reference" for row in r["rows"]]
    rows = [row for r in recs.values() if r and r["kwargs"]["kind"] == "actual" for row in r["rows"]]
    res = judge(ref_rows, rows, reps, n_ref)
    complete = res["complete"] and not missing and not errors and len(commits) == 1 and not dirty
    rep = {"study": "phase-5 S4, T_v size on the learned path (post-hoc fixture)", "complete": complete,
           "missing_tasks": missing, "error_tasks": errors, "commits": sorted(c for c in commits if c),
           "dirty": dirty, "result": res, "passed": bool(complete and res["passed"]), "provenance": provenance(),
           "flags": FLAGS, "seconds": float(sum(r["seconds"] for r in recs.values() if r))}
    io.write_json(str(out), io.jsonable(rep))
    return rep


SMOKE = [{"kind": "reference", "i0": 900000, "n": 2}, {"kind": "actual", "i0": 900000, "n": 2}]
SMOKE_CONFIG = {"exposure": 2000, "mc_events": 4000}


def local(out: Path) -> dict:
    """Two reference toys and two repetitions at a small MC size (`smoke`: exercises every step; never the study)."""
    t0 = time.time()
    d = out.parent / (out.stem + "_tasks")
    for i in range(len(SMOKE)):
        run_task(i, d, SMOKE, SMOKE_CONFIG)
    rep = merge(d, out, SMOKE, reps=sum(t["n"] for t in SMOKE if t["kind"] == "actual"),
                n_ref=sum(t["n"] for t in SMOKE if t["kind"] == "reference"))
    rep.update(label="smoke", seconds=time.time() - t0)
    io.write_json(str(out), io.jsonable(rep))
    return rep


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--task", type=int)
    ap.add_argument("--merge")
    ap.add_argument("--local", dest="smoke", action="store_true")
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    if args.list:
        print(json.dumps([{"task": i, **kw} for i, kw in enumerate(TASKS)]))
        return 0
    if not args.out:
        ap.error("--out is required with --task, --merge and --local")
    if args.task is not None:
        r = run_task(args.task, Path(args.out))
        print(json.dumps({"task": r["task"], "status": r["status"], "seconds": r["seconds"]}))
        return 0 if r["status"] == "ok" else 1
    if args.merge:
        r = merge(Path(args.merge), Path(args.out))
        print(json.dumps({"complete": r["complete"], "passed": r["passed"], "missing": len(r["missing_tasks"])}))
        return 0 if r["passed"] else 1
    if args.smoke:
        r = local(Path(args.out))
        print(json.dumps({"label": "smoke", "seconds": r["seconds"], "complete": r["complete"],
                          "errors": r["error_tasks"]}))
        return 0 if not r["error_tasks"] else 1
    ap.error("one of --list, --task, --merge, --local")
    return 2


if __name__ == "__main__":
    sys.exit(main())
