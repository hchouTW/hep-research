"""Study S4 of phase 5 (optional, ambiguity L9; task card `docs/dev/simulator-calibration/simcal-tasks/phase-5.md`,
"Studies to register before their runs"): the size of T_v on the learned path, where the toys retrain each replica's
classifier (independent training MC and initialization seed, section 6.6 line 1192; no replica shared between toys,
A25 (4)) and draw N(0, V_learn^bias) once (line 1209; only its scale is tested, A25 (2)). Acceptance as section 8.7
note 4 (line 2063): the rejection rate within alpha +- 25% over >= 10^4 repetitions. Also the post-hoc fixture as a
fit problem (`posthoc_problem`), shared by the unit tests of the learned path. Not a unit test module.

Design (the phase-2 form of note 4, calibration 12 of calibration_phase2_cals_b.py): the reference distribution of
T_v is built once from N_REF complete holdout toys (validate.holdout_toy) around the fit of one nominal problem at the
truth; each repetition is an independent actual experiment: its own nominal MC and trained classifiers, calibration
and validation data generated by the true simulator at the truth (no MC noise, no classifier error), the section 7.3
fit, T_v with its own C_r^+, and the p-value against the pooled reference. Reported controls (not pass conditions):
the same repetitions against a reference whose toys neither retrain nor draw the bias (`no-learned-toys`).

  python3 calibration_phase5_tv.py --list                        the task table (JSON)
  python3 calibration_phase5_tv.py --task K --out DIR            one task of the array
  python3 calibration_phase5_tv.py --merge DIR --out FILE        merge and judge (exit 0 passed, 1 failed/incomplete)
  python3 calibration_phase5_tv.py --local --out FILE            a tiny smoke (`smoke`; never judged as the study)

Tasks: tasks 0..N_REF_TASKS-1 make reference toys (both constructions), the rest actual repetitions. Seeds: toy or
repetition i of kind j uses SeedSequence([SEED0, j, i]); no stream is shared. Every record is `synthetic` and
`provisional-thresholds`.
"""
