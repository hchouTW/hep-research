#!/usr/bin/env python3
"""BIG and SLIM fitted with the USINE provider to SYNTHETIC Asimov B/C data (cr-propagation C2U), recorded for tests.

The study behind acceptance entries C2U-1 to C2U-3: an Asimov B/C dataset is generated by the USINE provider at a
BIG point (reacceleration interior, convection on its physical boundary V_c = 0), and propagation_fit.py fits the
families BIG (D0, delta, V_A, V_c free) and SLIM (D0, delta free, V_A = V_c = 0) to it with the provider, with a
profile interval of V_c (one-sided width on the boundary) and toy-calibrated delta chi2 of both families on a
polynomial response model validated against the provider (its error added to the covariance, P10). Both families
share one transport block: the provider's harmonized-v1 default with one ILLUSTRATIVE low-rigidity diffusion break,
held fixed because the provider's domain has no break parameters. Every input is ILLUSTRATIVE; nothing is fitted to
real data.

The live run needs USINE (HEP_USINE_BIN, HEP_USINE_DATA) and keeps every run's computational-run artifact under
HEP_USINE_RUN_DIR; it writes the recorded study (dataset, configuration, fit result with the per-evaluation records,
the USINE prediction at the truth) to --record, from which test_propagation_fit.py checks the criteria offline.

Usage:
  python3 usine_family_study.py --registry REGISTRY.json --cache-dir DIR --out DIR [--record FILE]
      [--max-evaluations 1200] [--family-toys 200]
Exit codes: 0 written; 1 the fit failed; 2 bad input or USINE not configured.
"""
from __future__ import annotations

import argparse
import copy
import json
import math
import os
import sys
from pathlib import Path

PLUGIN = Path(__file__).resolve().parents[3]
sys.dont_write_bytecode = True
for entry in (str(PLUGIN), str(PLUGIN / "skills" / "hep-statistics" / "scripts")):
    if entry not in sys.path:
        sys.path.insert(0, entry)

PROVIDER, VERSION = "usine", "0.2.0"
RECORD = PLUGIN / "tests" / "adapters" / "fixtures" / "cr_propagation" / "c2u" / "usine-family-study.json"
LOW_BREAK = {"kind": "low", "R_break_gv": 5.0, "delta_below": 0.0, "s": 0.05, "s_convention": "usine"}
TRUTH = {"D0_cm2_s": 3.0e28, "delta": 0.45, "V_A_kms": 70.0, "V_c_kms": 0.0}
START = {"D0_cm2_s": 2.4e28, "delta": 0.48, "V_A_kms": 60.0, "V_c_kms": 2.0}
FIXED = {"L_kpc": 4.0, "eta": 1.0}
STEPS = {"D0_cm2_s": 0.003, "delta": 0.001, "V_A_kms": 0.3, "V_c_kms": 0.3}
FAMILIES = [{"name": "BIG", "free": ["D0_cm2_s", "delta", "V_A_kms", "V_c_kms"], "fixed": {}},
            {"name": "SLIM", "free": ["D0_cm2_s", "delta"], "fixed": {"V_A_kms": 0.0, "V_c_kms": 0.0}}]


def edges() -> list[float]:
    """15 bins equal in ln(E_k/n) from 0.3 to 300 GeV/n."""
    lo, hi, n = math.log(0.3), math.log(300.0), 15
    return [float(f"{math.exp(lo + (hi - lo) * k / n):.6g}") for k in range(n + 1)]


def transport() -> dict:
    """The provider's harmonized-v1 default transport with the ILLUSTRATIVE low break, family BIG (the generator)."""
    sys.path.insert(0, str(PLUGIN / "adapters" / "cr-propagation" / "assets"))
    import usine_provider
    doc = copy.deepcopy(usine_provider.DEFAULT_TRANSPORT)
    doc["diffusion"]["breaks"] = [dict(LOW_BREAK)]
    doc["family"] = "BIG"
    doc["free"] = list(FAMILIES[0]["free"])
    return doc


def asimov_record(prediction: dict, labels) -> dict:
    from contracts import CONTRACTS_VERSION
    y = prediction["values"]["values"]
    return {
        "contract_version": CONTRACTS_VERSION, "artifact_id": "c2u-usine-asimov-bc", "artifact_type": "dataset-record",
        "objective": "SYNTHETIC Asimov B/C points from the USINE provider at an ILLUSTRATIVE BIG point (C2U)",
        "bindings": {"experiments": [], "theory": []},
        "versions": {"plugin": "", "contracts": CONTRACTS_VERSION, "profiles": {}},
        "provenance": {"producer_skill": "hep-statistics", "created": "2026-10-28", "evidence_ids": []},
        "inputs": [], "outputs": [], "status": sorted(set(labels) | {"synthetic", "asimov"}), "unresolved_inputs": [],
        "extension": {"dataset_id": "synthetic:c2u-usine-asimov-bc", "source_evidence_ids": [],
                      "observable": copy.deepcopy(prediction["observable"]),
                      "data": {"edges": prediction["values"]["edges"], "values": y, "unit": "1",
                               "uncertainties": [
                                   {"name": "statistical", "kind": "statistical", "correlation": "uncorrelated",
                                    "values": [0.04 * v for v in y]},
                                   {"name": "normalization", "kind": "systematic", "correlation": "fully-correlated",
                                    "values": [0.02 * v for v in y]}]},
                      "covariance": {"status": "present"}, "status": "synthetic"}}


def config(record: dict, family_toys: int, runs_ref=None) -> dict:
    """The fit configuration. The provider's parameter_point keys usine_run and transport_substitutes record how each
    point was run (they change with the point, for example when V_A = 0 switches reacceleration off), so they are
    run-record keys, kept in the gate record and not compared with the data's conditions."""
    cfg = {"provider": {"id": PROVIDER, "version": VERSION}, "transport": transport(),
           "datasets": [{"name": "bc-asimov", "measurement": record, "observable": "B/C"}],
           "parameters": {n: {"start": START[n], "scale": "log" if n == "D0_cm2_s" else "linear", "step": STEPS[n]}
                          for n in TRUTH},
           "fixed": dict(FIXED), "families": copy.deepcopy(FAMILIES), "intervals": ["V_c_kms"],
           "response_model": {"kind": "polynomial", "degree": 3, "design_points": 96, "validation_points": 20,
                              "tolerance_sigma": 0.05},
           "family_toys": {"n": family_toys, "seed": 20261028, "alpha": 0.05},
           "gate_plan": {"measurement_conditions": {}},
           "run_record_keys": ["usine_run", "transport_substitutes"]}
    if runs_ref is not None:
        cfg["computational_runs"] = str(runs_ref)
    return cfg


def generate(registry: str, cache_dir: str) -> tuple[dict, dict]:
    """The provider's B/C at the truth (one USINE run); (prediction, response result)."""
    from core.provider.runner import ProviderRunner
    e = edges()
    req = {"protocol": "cr-provider/1", "provider": PROVIDER, "provider_version": VERSION, "transport": transport(),
           "points": [dict(TRUTH, **FIXED)],
           "observables": [{"id": "B/C", "axis": "ekn", "unit": "GeV/n", "bins": [[a, b] for a, b in zip(e, e[1:])]}],
           "want": ["lis"], "seed": None}
    with ProviderRunner(registry, cache_dir=cache_dir) as runner:
        res = runner.evaluate(req)["results"][0]
        sent = runner.stats["points_sent"]
    if res.get("status") != "ok":
        raise SystemExit(f"the truth point failed: {res.get('reason')} {res.get('detail')}")
    return res, {"points_sent": sent}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--registry", required=True, help="provider registry (tools/provider_registry.py --write)")
    ap.add_argument("--cache-dir", required=True, help="provider cache folder (outside the repository)")
    ap.add_argument("--out", required=True, type=Path, help="folder for the fit outputs (outside the repository)")
    ap.add_argument("--record", type=Path, default=RECORD, help="recorded study to write (default: the test fixture)")
    ap.add_argument("--max-evaluations", type=int, default=1200, help="cap on USINE evaluations of the fit")
    ap.add_argument("--family-toys", type=int, default=200, help="toys per family for the delta chi2 calibration")
    args = ap.parse_args(argv)
    runs = os.environ.get("HEP_USINE_RUN_DIR")
    if not (os.environ.get("HEP_USINE_BIN") and os.environ.get("HEP_USINE_DATA") and runs):
        print(json.dumps({"status": "rejected", "error": "set HEP_USINE_BIN, HEP_USINE_DATA and HEP_USINE_RUN_DIR"}))
        return 2
    import propagation_fit as pf
    truth_res, gen = generate(args.registry, args.cache_dir)
    record = asimov_record(truth_res["predictions"][0], truth_res.get("labels") or [])
    cfg = config(record, args.family_toys, runs)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "config.json").write_text(json.dumps(cfg, indent=1) + "\n", encoding="utf-8")
    try:
        result = pf.run(cfg, args.out, args.registry, cache_dir=args.cache_dir, max_evaluations=args.max_evaluations,
                        out_dir=args.out, cfg_ref="config.json")
    except (pf.FitRefused, pf.FitInputError, pf.FitIncomplete) as exc:
        print(json.dumps({"status": "failed", "error": str(exc), "reason": getattr(exc, "reason", None)}))
        return 1
    cfg.pop("computational_runs", None)   # a local folder: not recorded
    doc = {"study": "C2U BIG and SLIM with the USINE provider (SYNTHETIC Asimov, ILLUSTRATIVE inputs)",
           "truth": dict(TRUTH, **FIXED), "generating_family": "BIG", "truth_evaluation": truth_res["evaluation"],
           "truth_prediction": truth_res["predictions"][0], "config": cfg,
           "usine_evaluations": {"truth": gen["points_sent"], "fit": result["provider_evaluations"]["points_sent"]},
           "result": pf._jsonable(result)}
    args.record.parent.mkdir(parents=True, exist_ok=True)
    args.record.write_text(json.dumps(doc, indent=1) + "\n", encoding="utf-8")
    print(json.dumps({"status": result["status"], "record": str(args.record),
                      "usine_points_sent": doc["usine_evaluations"]}))
    return 0 if result["status"] == "ok" else 1


if __name__ == "__main__":
    sys.exit(main())
